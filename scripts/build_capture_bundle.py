"""Assemble self-contained capture function; no dynamic evaluation in extension."""
import argparse
from pathlib import Path

base = Path(__file__).resolve().parents[1] / "BrowserExtension/CaptureEngine"
entry = (base / "capture.js").read_text(encoding="utf-8")
marker = "  /* @capture-modules */"
assert entry.count(marker) == 1
helpers = "\n".join((base / name).read_text(encoding="utf-8").rstrip() for name in ("layout.js", "assets.js", "svg.js"))
document_capture = entry.replace(marker, helpers)
indented = "\n".join("  " + line if line else "" for line in document_capture.rstrip().split("\n"))
generated = """// Generated by scripts/build_capture_bundle.py; do not edit.
async function capture(mode, options = {}) {
""" + indented + r"""
  if (!options.returnOutcome) return captureDocument(mode, options);
  try {
    return {capture: await captureDocument(mode, options)};
  } catch (error) {
    const code = typeof error?.message === 'string' && /^error_[a-z_]+$/.test(error.message)
      ? error.message : 'error_capture';
    return {error:code};
  }
}
"""
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
path = base / "injected.js"
if args.check:
    if not path.exists() or path.read_text(encoding="utf-8") != generated:
        raise SystemExit("Capture bundle stale; run python3 scripts/build_capture_bundle.py")
    print("Capture bundle matches source modules")
else:
    path.write_text(generated, encoding="utf-8")
